// Runs after `vite build`, on dist/. Everything here is derived from
// public/case-study/data/products.json, so adding a case study there is all
// it takes — the next build gives it:
//
//   1. its own page, dist/case-study/<slug>.html, with the product's title,
//      description and share image written into the HTML. WhatsApp, LinkedIn
//      and other link previews do not run JavaScript, so product.html?p=<slug>
//      could only ever show them the generic "Case Study | White Dot".
//   2. a share image, dist/case-study/og/<slug>.jpg — the committed 3D render
//      if there is one (npm run og:render), otherwise a name card drawn here.
//   3. a line in dist/sitemap.xml.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { ROOT, SITE, loadCaseStudies, composeCard, escapeXml } from "./lib/case-study-seo.mjs";

const dist = resolve(ROOT, "dist");
const templatePath = resolve(dist, "case-study/product.html");
if (!existsSync(templatePath)) {
  console.error("[build-seo] dist/case-study/product.html is missing — run vite build first.");
  process.exit(1);
}

const studies = loadCaseStudies();
if (studies.length === 0) {
  console.error("[build-seo] no live case studies found in products.json — refusing to write an empty sitemap.");
  process.exit(1);
}

// ── 1. Per-product pages ────────────────────────────────────────────────────
const template = readFileSync(templatePath, "utf8");
const HEAD_TAGS = [
  /[ \t]*<title\b[^>]*>[\s\S]*?<\/title>[ \t]*\n?/i,
  /[ \t]*<meta\b[^>]*\bname="description"[^>]*>[ \t]*\n?/i,
  /[ \t]*<link\b[^>]*\brel="canonical"[^>]*>[ \t]*\n?/i,
  /[ \t]*<meta\b[^>]*\bproperty="og:[^"]*"[^>]*>[ \t]*\n?/gi,
  /[ \t]*<meta\b[^>]*\bname="twitter:[^"]*"[^>]*>[ \t]*\n?/gi,
];

function pageFor(study) {
  let html = template;
  for (const tag of HEAD_TAGS) html = html.replace(tag, "");
  const t = escapeXml(study.title);
  const d = escapeXml(study.description);
  // The ids are kept: product.html's script updates these same tags.
  const head = `
  <title id="pageTitle">${t}</title>
  <meta id="metaDesc" name="description" content="${d}" />
  <link id="canonicalLink" rel="canonical" href="${study.url}" />
  <meta property="og:type" content="article" />
  <meta property="og:site_name" content="White Dot" />
  <meta id="ogTitle" property="og:title" content="${t}" />
  <meta id="ogDesc" property="og:description" content="${d}" />
  <meta id="ogUrl" property="og:url" content="${study.url}" />
  <meta property="og:image" content="${study.image}" />
  <meta property="og:image:width" content="1200" />
  <meta property="og:image:height" content="630" />
  <meta property="og:image:alt" content="${escapeXml(`${study.name} — LIMEX case study by White Dot`)}" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${t}" />
  <meta name="twitter:description" content="${d}" />
  <meta name="twitter:image" content="${study.image}" />
  <script>window.__WD_SLUG__=${JSON.stringify(study.slug)};window.__WD_STATIC_PAGES__=true;</script>`;
  const at = html.search(/<meta\b[^>]*\bname="viewport"[^>]*>/i);
  if (at < 0) throw new Error("product.html has no viewport meta to anchor the head tags to");
  const end = html.indexOf(">", at) + 1;
  return html.slice(0, end) + head + html.slice(end);
}

mkdirSync(resolve(dist, "case-study/og"), { recursive: true });
let drawn = 0;
for (const study of studies) {
  writeFileSync(resolve(dist, `case-study/${study.slug}.html`), pageFor(study));
  const image = resolve(dist, `case-study/og/${study.slug}.jpg`);
  if (!existsSync(image)) {
    writeFileSync(image, await composeCard(study, null));
    drawn += 1;
  }
}
// product.html?p=<slug> keeps working; this tells it the per-product pages
// exist so it can show the shareable address.
writeFileSync(
  templatePath,
  template.replace(/(<meta\b[^>]*\bname="viewport"[^>]*>)/i, "$1\n  <script>window.__WD_STATIC_PAGES__=true;</script>"),
);

// ── 2. Sitemap ──────────────────────────────────────────────────────────────
const urls = [
  { loc: `${SITE}/`, priority: "1.0", changefreq: "weekly" },
  { loc: `${SITE}/case-study/`, priority: "0.9", changefreq: "weekly" },
  ...studies.map((s) => ({ loc: s.url, priority: "0.8", image: s.image, title: s.name })),
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-seo.mjs from public/case-study/data/products.json — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${urls
  .map(
    (u) => `  <url>
    <loc>${escapeXml(u.loc)}</loc>${u.changefreq ? `\n    <changefreq>${u.changefreq}</changefreq>` : ""}
    <priority>${u.priority}</priority>${u.image ? `\n    <image:image><image:loc>${escapeXml(u.image)}</image:loc></image:image>` : ""}
  </url>`,
  )
  .join("\n")}
</urlset>
`;
writeFileSync(resolve(dist, "sitemap.xml"), sitemap);

console.log(
  `[build-seo] ${studies.length} case-study pages, sitemap with ${urls.length} URLs, ` +
    `${drawn} share image(s) drawn as name cards (run "npm run og:render" for 3D renders).`,
);
