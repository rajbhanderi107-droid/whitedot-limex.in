/* Generates the entry page and manifest for each standalone book app.
 *
 * Run with `node scripts/build-book-apps.mjs`. The files it writes are
 * committed and are real Vite build inputs — the point of generating them is
 * that three near-identical HTML heads cannot drift apart by hand.
 *
 * Each book gets its own directory, so /route/, /visits/, /leads/ and
 * /customers/ are four separate installable apps with their own name, icon
 * and start page, all running the same code against the same records.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const BOOKS = [
  {
    key: "route", dir: "route",
    name: "LIMEX Route Book", short: "Route Book", theme: "#4f9a35",
    description: "The WhiteDot field book: Gujarat plastics manufacturers in drivable legs, ticked and noted as you go.",
  },
  {
    key: "visits", dir: "visits",
    name: "LIMEX Visit Follow-ups", short: "Visits", theme: "#8f6fb5",
    description: "Every company a WhiteDot visit touched, and what it is waiting on next.",
  },
  {
    key: "leads", dir: "leads",
    name: "LIMEX Lead Book", short: "Lead Book", theme: "#e0a040",
    description: "The WhiteDot deals in play: next step, expected tonnage and the rate quoted.",
  },
  {
    key: "customers", dir: "customers",
    name: "LIMEX Customer Book", short: "Customer Book", theme: "#2f9fc0",
    description: "WhiteDot customers and their LIMEX orders in metric tonnes, with Excel and Word exports.",
  },
];

/* Only what these apps actually use: the API, Google sign-in, and the two
   font hosts. No analytics, no video, no third-party frames. */
const CSP = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'wasm-unsafe-eval' https://accounts.google.com https://www.gstatic.com",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://api.fontshare.com",
  "font-src 'self' data: https://fonts.gstatic.com https://api.fontshare.com https://cdn.fontshare.com",
  "img-src 'self' data: https: blob:",
  "connect-src 'self' https://api.whitedotindia.in http://localhost:4000 https://accounts.google.com https://www.gstatic.com blob:",
  "frame-src 'self' https://accounts.google.com",
  "worker-src 'self' blob:",
  "child-src 'self' https://accounts.google.com blob:",
  "object-src 'none'",
  "base-uri 'self'",
].join("; ");

const html = (b) => `<!doctype html>
<!-- Generated by scripts/build-book-apps.mjs — edit that, not this file. -->
<html lang="en" data-book="${b.key}">
  <head>
    <meta charset="UTF-8" />
    <meta http-equiv="Content-Security-Policy" content="${CSP};" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover" />
    <title>${b.name} — WhiteDot</title>
    <meta name="description" content="${b.description}" />
    <!-- An internal sales tool. Anyone with the link can open it; the records
         behind it still need a WhiteDot login. It has no business in search. -->
    <meta name="robots" content="noindex, nofollow" />

    <link rel="manifest" href="manifest.webmanifest" />
    <meta name="theme-color" content="#080808" />
    <meta name="color-scheme" content="dark" />
    <!-- The website's own logo on a dark tile, one per book. There is no SVG
         variant: the mark is a raster logo file, and inlining it as a data
         URI would cost a quarter of a megabyte per page for no gain. -->
    <link rel="icon" type="image/png" sizes="192x192" href="/assets/icons/${b.key}-192.png" />

    <!-- iOS: Add to Home Screen, then it opens without Safari's chrome. -->
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="apple-mobile-web-app-title" content="${b.short}" />
    <link rel="apple-touch-icon" href="/assets/icons/${b.key}-apple-180.png" />

    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link rel="preconnect" href="https://api.fontshare.com" />
    <link rel="preconnect" href="https://cdn.fontshare.com" crossorigin />
    <!-- One request per host, discovered in the head so they load in
         parallel — same set as the main site, kept in step by hand here
         because these pages are generated from this one template. -->
    <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Cinzel:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500;600&family=Inter:wght@300;400;500;600&family=JetBrains+Mono:ital,wght@0,400;0,500;0,700;1,400;1,500&family=Zen+Kaku+Gothic+New:wght@300;400;500;700;900&display=swap" />
    <link rel="stylesheet" href="https://api.fontshare.com/v2/css?f[]=satoshi@300,400,500,700,900&f[]=satoshi-italic@400,500,700&f[]=boska@400,500,700,900&f[]=boska-italic@400,500,700&display=swap" />
    <style>
      html, body { margin: 0; padding: 0; background: #080808; }
    </style>
  </head>
  <body>
    <div id="root"></div>
    <noscript>The ${b.name} needs JavaScript. Open it in any modern browser.</noscript>
    <script type="module" src="/src/books/main.tsx"></script>
  </body>
</html>
`;

const manifest = (b) => JSON.stringify({
  id: `/${b.dir}/`,
  name: `${b.name} — WhiteDot`,
  short_name: b.short,
  description: b.description,
  start_url: `/${b.dir}/`,
  scope: `/${b.dir}/`,
  display: "standalone",
  orientation: "portrait-primary",
  background_color: "#080808",
  theme_color: b.theme,
  categories: ["business", "productivity"],
  icons: [
    { src: `/assets/icons/${b.key}-192.png`, sizes: "192x192", type: "image/png", purpose: "any" },
    { src: `/assets/icons/${b.key}-512.png`, sizes: "512x512", type: "image/png", purpose: "any" },
    { src: `/assets/icons/${b.key}-512.png`, sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
}, null, 2) + "\n";

for (const b of BOOKS) {
  mkdirSync(resolve(ROOT, b.dir), { recursive: true });
  writeFileSync(resolve(ROOT, b.dir, "index.html"), html(b));
  mkdirSync(resolve(ROOT, "public", b.dir), { recursive: true });
  writeFileSync(resolve(ROOT, "public", b.dir, "manifest.webmanifest"), manifest(b));
  console.log(`${b.dir}/index.html + public/${b.dir}/manifest.webmanifest`);
}
